CREATE TABLE clients(
id SERIAL PRIMARY KEY,
company_name VARCHAR(255),
contact_person VARCHAR(255),
email VARCHAR(255),
phone VARCHAR(11),
address VARCHAR(255)
);

CREATE table project_statuses(
id SERIAL PRIMARY KEY,
name VARCHAR(255)
);

CREATE TABLE advertising_projects(
id SERIAL PRIMARY KEY,
name VARCHAR(255),
description TEXT,
start_date DATE,
end_date DATE,
budget decimal,
status_id integer REFERENCES project_statuses(id),
client_id serial REFERENCES clients(id)
);

CREATE table task_statuses(
id SERIAL PRIMARY KEY,
name VARCHAR(255)
);

CREATE TABLE tasks(
id SERIAL PRIMARY KEY,
title VARCHAR(255),
description TEXT,
deadline DATE,
status_id integer REFERENCES task_statuses(id),
assigned_to VARCHAR(255),
advertising_projects_id SERIAL REFERENCES advertising_projects(id)
);


